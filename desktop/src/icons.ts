export type IconName = keyof typeof PATHS;

/** An icon as markup, sized by the surrounding font unless `size` is given. */
export function icon(name: IconName, size = 18): string {
  return (
    `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false">${PATHS[name]}</svg>`
  );
}

/**
 * The text-colour icon: an "A" over a bar in the colour it will apply.
 *
 * Not from Lucide. The bar is the point -- it is how every mail client's
 * colour button says what a click will do -- and it is a separate element so
 * the composer can recolour it as the caret moves.
 */
export function colourIcon(size = 18): string {
  return (
    `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false"><path d="m6 16 6-13 6 13"/><path d="M8.5 11h7"/>` +
    `<rect class="colour-bar" x="3" y="19" width="18" height="4" rx="1" ` +
    `fill="currentColor" stroke="none"/></svg>`
  );
}
